// Silhouettes dessinées pour les objets dont l'emoji trahit la forme : vue de face au lieu
// du profil, tête seule, personnages génériques. Les coordonnées sont libres : la boîte
// englobante est mesurée au rendu, puis le dessin est calé sur le rapport réel de l'objet.
export type Part = string | { d: string; w: number }

const n = (v: number) => +v.toFixed(2)

function E(cx: number, cy: number, rx: number, ry = rx, rot = 0): string {
  const t = (rot * Math.PI) / 180
  const [dx, dy] = [rx * Math.cos(t), rx * Math.sin(t)]
  const a = `${n(cx - dx)},${n(cy - dy)}`
  const b = `${n(cx + dx)},${n(cy + dy)}`
  return `M${a}A${rx},${ry} ${rot} 1 0 ${b}A${rx},${ry} ${rot} 1 0 ${a}Z`
}

function R(x: number, y: number, w: number, h: number, r = 0): string {
  return `M${x + r},${y}H${x + w - r}A${r},${r} 0 0 1 ${x + w},${y + r}V${y + h - r}A${r},${r} 0 0 1 ${x + w - r},${y + h}H${x + r}A${r},${r} 0 0 1 ${x},${y + h - r}V${y + r}A${r},${r} 0 0 1 ${x + r},${y}Z`
}

const P = (pts: string) => `M${pts}Z`
// trait épais à bouts ronds : membres, queues, mâts
const S = (pts: string, w: number): Part => ({ d: `M${pts}`, w })
const C = (d: string, w: number): Part => ({ d, w })

function star(cx: number, cy: number, r1: number, r2: number, k: number): string {
  const pts = Array.from({ length: 2 * k }, (_, i) => {
    const a = (i * Math.PI) / k
    const r = i % 2 ? r2 : r1
    return `${n(cx + r * Math.sin(a))},${n(cy - r * Math.cos(a))}`
  })
  return P(pts.join(' '))
}

